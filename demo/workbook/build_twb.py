"""Generate the "Sales Performance" legacy workbook as Tableau XML (.twb) and a packaged .twbx.

This reproduces, in XML, exactly what docs/demo-workbook-build-guide.md asks a person to build in
Tableau Desktop: one physical join, five relationships (logical layer / object graph), a data source
filter, a parameter, 13 calculated fields, six worksheets and one dashboard.

It mirrors the structure Tableau 2020.2+ writes (including the `_.fcp.<Feature>.true...` forward-
compatibility element names), but it is NOT Tableau-authored. Opening it in Tableau Desktop and
saving a copy produces the Tableau-normalised version (see fixtures/tableau/FIXTURE.md).

IDs are derived deterministically from fixed names, so the output is byte-reproducible.
"""

from __future__ import annotations

import csv
import uuid
import zipfile
from dataclasses import dataclass
from pathlib import Path

from lxml import etree

USER_NS = "http://www.tableausoftware.com/xml/user"
U = f"{{{USER_NS}}}"
FCP_TRUE = "_.fcp.ObjectModelEncapsulateLegacy.true..."
FCP_FALSE = "_.fcp.ObjectModelEncapsulateLegacy.false..."
NAMESPACE = uuid.UUID("6f1d3c2a-5b7e-4c1a-9d3e-2b8a4f6c0e11")
VERSION = "18.1"
SOURCE_BUILD = "2026.3.0 (generated by BIAssurance demo/workbook/build_twb.py)"

TABLES = ["ORDERS_HDR", "ord_lines", "PROD_MSTR", "prod_cat", "CUSTMR", "RGN_LKP", "RTN_LOG"]
DATE_FIELDS = {"OrdDt", "ShipDt", "RtnDt", "SignupDt"}
INT_FIELDS = {"QTY", "line_no", "RtnQty"}
REAL_FIELDS = {"UnitPx", "DiscPct", "UnitCost", "LineAmt", "OrdTotAmt", "ListPx", "StdCost", "RtnAmt"}
REMOTE_TYPE = {"string": "129", "integer": "20", "real": "5", "date": "133"}
DEFAULT_AGG = {"string": "Count", "integer": "Sum", "real": "Sum", "date": "Year"}


def _hex_id(name: str) -> str:
    return uuid.uuid5(NAMESPACE, name).hex.upper()


def _short_id(name: str, length: int = 28) -> str:
    alphabet = "0123456789abcdefghijklmnopqrstuvwxyz"
    n = uuid.uuid5(NAMESPACE, name).int
    out = []
    while len(out) < length:
        n, r = divmod(n, 36)
        out.append(alphabet[r])
        if n == 0:
            n = uuid.uuid5(NAMESPACE, name + str(len(out))).int
    return "".join(out)


def _guid(name: str) -> str:
    return "{" + str(uuid.uuid5(NAMESPACE, name)).upper() + "}"


def _datatype(col: str) -> str:
    if col in DATE_FIELDS:
        return "date"
    if col in INT_FIELDS:
        return "integer"
    if col in REAL_FIELDS:
        return "real"
    return "string"


@dataclass(frozen=True)
class Field:
    table: str        # e.g. ORDERS_HDR
    remote: str       # CSV header
    local: str        # Tableau local name without brackets, e.g. "OrdID (ord_lines.csv)"
    datatype: str
    ordinal: int

    @property
    def object_id(self) -> str:
        return f"{self.table}.csv_{_hex_id(self.table)}"


def read_headers(csv_dir: Path) -> dict[str, list[str]]:
    headers = {}
    for t in TABLES:
        with open(csv_dir / f"{t}.csv", encoding="utf-8", newline="") as fh:
            headers[t] = next(csv.reader(fh))
    return headers


def resolve_fields(headers: dict[str, list[str]]) -> list[Field]:
    """Tableau keeps the first occurrence of a column name and suffixes later ones with the file."""
    seen: set[str] = set()
    fields = []
    for t in TABLES:
        for i, col in enumerate(headers[t]):
            local = col if col not in seen else f"{col} ({t}.csv)"
            seen.add(col)
            fields.append(Field(t, col, local, _datatype(col), i))
    return fields


# --- calculated fields (formulas exactly as in the build guide) --------------------------------

@dataclass(frozen=True)
class Calc:
    caption: str
    formula: str          # with references by caption: {{Caption}} for other calcs
    datatype: str
    role: str = "measure"
    type: str = "quantitative"

    @property
    def internal(self) -> str:
        # Tableau names calcs Calculation_<19 digits>; derive a stable one.
        return "Calculation_" + str(uuid.uuid5(NAMESPACE, self.caption).int)[:19]


CALCS = [
    Calc("Line Gross", "[QTY] * [UnitPx]", "real"),
    Calc("Discount Amount", "[QTY] * [UnitPx] * ZN([DiscPct])", "real"),
    Calc("Line Net", "{{Line Gross}} - {{Discount Amount}}", "real"),
    Calc("Line Cost", "[QTY] * [UnitCost]", "real"),
    Calc("Gross Profit", "{{Line Net}} - {{Line Cost}}", "real"),
    Calc("Net Revenue", "SUM({{Line Net}})", "real"),
    Calc("GP Margin %", "SUM({{Gross Profit}}) / SUM({{Line Net}})", "real"),
    Calc("Orders", "COUNTD([OrdID])", "integer"),
    Calc("AOV", "SUM({{Line Net}}) / COUNTD([OrdID])", "real"),
    Calc("Return Rate", "SUM([RtnAmt]) / SUM({{Line Net}})", "real"),
    Calc("Customer First Order", "{ FIXED [CustNo] : MIN([OrdDt]) }", "date", "dimension", "ordinal"),
    Calc("Cohort Year", "YEAR({{Customer First Order}})", "integer", "dimension", "ordinal"),
    Calc("Running Net Revenue", "RUNNING_SUM(SUM({{Line Net}}))", "real"),
]
CALC_BY_CAPTION = {c.caption: c for c in CALCS}
PERCENT_FORMAT = {"GP Margin %", "Return Rate"}


def stored_formula(calc: Calc) -> str:
    """Tableau stores references to other calcs by internal name."""
    out = calc.formula
    for c in CALCS:
        out = out.replace("{{" + c.caption + "}}", f"[{c.internal}]")
    return out


def calc_dependencies(caption: str) -> list[Calc]:
    """The calc and every calc it references, transitively (Tableau lists them all as dependencies)."""
    result: list[Calc] = []

    def visit(cap: str) -> None:
        c = CALC_BY_CAPTION[cap]
        for other in CALCS:
            if "{{" + other.caption + "}}" in c.formula and other not in result:
                visit(other.caption)
        if c not in result:
            result.append(c)

    visit(caption)
    return result


# --- XML helpers --------------------------------------------------------------------------------

def sub(parent, tag, attrib=None, text=None, **kw):
    el = etree.SubElement(parent, tag, {k: str(v) for k, v in (attrib or {}).items()})
    for k, v in kw.items():
        el.set(k.replace("_", "-"), str(v))
    if text is not None:
        el.text = text
    return el


class Workbook:
    def __init__(self, csv_dir_for_connection: str, headers: dict[str, list[str]]):
        self.ds_name = "federated." + _short_id("datasource")
        self.conn_name = "textscan." + _short_id("connection")
        self.directory = csv_dir_for_connection
        self.fields = resolve_fields(headers)
        self.by_local = {f.local: f for f in self.fields}

    # field reference helpers
    def ref(self, inner: str) -> str:
        return f"[{self.ds_name}].[{inner}]"

    def calc_inst(self, caption: str, derivation: str = "usr", pivot: str = "qk") -> str:
        return f"{derivation}:{CALC_BY_CAPTION[caption].internal}:{pivot}"

    # --- datasource -----------------------------------------------------------------------------
    def _table_relation(self, parent, tag: str, table: str):
        rel = sub(parent, tag, {"connection": self.conn_name, "name": f"{table}.csv",
                                "table": f"[{table}#csv]", "type": "table"})
        cols = sub(rel, "columns", {"character-set": "UTF-8", "header": "yes", "locale": "en_IN",
                                    "separator": ","})
        for f in (f for f in self.fields if f.table == table):
            sub(cols, "column", {"datatype": f.datatype, "name": f.remote, "ordinal": f.ordinal})
        return rel

    def _join_relation(self, parent):
        join = sub(parent, "relation", {"join": "inner", "type": "join"})
        clause = sub(join, "clause", {"type": "join"})
        expr = sub(clause, "expression", {"op": "="})
        sub(expr, "expression", {"op": "[ORDERS_HDR.csv].[OrdID]"})
        sub(expr, "expression", {"op": "[ord_lines.csv].[OrdID]"})
        self._table_relation(join, "relation", "ORDERS_HDR")
        self._table_relation(join, "relation", "ord_lines")
        return join

    def _object_id(self, table: str) -> str:
        # The joined logical table is named after its first physical table.
        return f"{table}.csv_{_hex_id(table)}"

    def build_datasource(self, datasources):
        ds = sub(datasources, "datasource", {"caption": "ORDERS_HDR+ (legacy_csv)", "inline": "true",
                                             "name": self.ds_name, "version": VERSION})
        conn = sub(ds, "connection", {"class": "federated"})
        named = sub(sub(conn, "named-connections"), "named-connection",
                    {"caption": "legacy_csv", "name": self.conn_name})
        sub(named, "connection", {"class": "textscan", "directory": self.directory,
                                  "filename": "ORDERS_HDR.csv", "password": "", "server": ""})

        # Legacy (pre-relationships) readers see only the joined first object.
        self._join_relation_into(conn, FCP_FALSE + "relation")
        coll = sub(conn, FCP_TRUE + "relation", {"type": "collection"})
        self._join_relation(coll)
        for t in TABLES[2:]:
            self._table_relation(coll, "relation", t)

        cols = sub(conn, "cols")
        for f in self.fields:
            sub(cols, "map", {"key": f"[{f.local}]", "value": f"[{f.table}.csv].[{f.remote}]"})

        records = sub(conn, "metadata-records")
        for f in self.fields:
            r = sub(records, "metadata-record", {"class": "column"})
            sub(r, "remote-name", text=f.remote)
            sub(r, "remote-type", text=REMOTE_TYPE[f.datatype])
            sub(r, "local-name", text=f"[{f.local}]")
            sub(r, "parent-name", text=f"[{f.table}.csv]")
            sub(r, "remote-alias", text=f.remote)
            sub(r, "ordinal", text=str(f.ordinal))
            sub(r, "local-type", text=f.datatype)
            sub(r, "aggregation", text=DEFAULT_AGG[f.datatype])
            sub(r, "contains-null", text="true")
            owner = "ORDERS_HDR" if f.table in ("ORDERS_HDR", "ord_lines") else f.table
            sub(r, FCP_TRUE + "object-id", text=f"[{self._object_id(owner)}]")

        sub(ds, "aliases", {"enabled": "yes"})
        for f in self.fields:
            if f.datatype == "date":
                sub(ds, "column", {"datatype": "date", "name": f"[{f.local}]", "role": "dimension",
                                   "type": "ordinal"})
        for c in CALCS:
            self._calc_column(ds, c)

        # Data source filter: exclude cancelled orders.
        flt = sub(ds, "filter", {"class": "categorical", "column": "[OrdStat]", "filter-group": "2"})
        gf = sub(flt, "groupfilter", {"function": "except", U + "ui-domain": "database",
                                      U + "ui-enumeration": "exclusive", U + "ui-marker": "enumerate"})
        sub(gf, "groupfilter", {"function": "level-members", "level": "[OrdStat]"})
        sub(gf, "groupfilter", {"function": "member", "level": "[OrdStat]", "member": '"X"'})

        sub(ds, "layout", {"dim-ordering": "alphabetic", "measure-ordering": "alphabetic",
                           "show-structure": "true"})
        sem = sub(ds, "semantic-values")
        sub(sem, "semantic-value", {"key": "[Country].[Name]", "value": '"India"'})

        graph = sub(ds, FCP_TRUE + "object-graph")
        objects = sub(graph, "objects")
        joined = sub(objects, "object", {"caption": "ORDERS_HDR.csv", "id": self._object_id("ORDERS_HDR")})
        self._join_relation(sub(joined, "properties", {"context": ""}))
        for t in TABLES[2:]:
            obj = sub(objects, "object", {"caption": f"{t}.csv", "id": self._object_id(t)})
            self._table_relation(sub(obj, "properties", {"context": ""}), "relation", t)
        rels = sub(graph, "relationships")
        for first, second, pairs in [
            ("ORDERS_HDR", "PROD_MSTR", [("ProdCode", "ProdCode (PROD_MSTR.csv)")]),
            ("PROD_MSTR", "prod_cat", [("CatCd", "CatCd (prod_cat.csv)")]),
            ("ORDERS_HDR", "CUSTMR", [("CustNo", "CustNo (CUSTMR.csv)")]),
            ("CUSTMR", "RGN_LKP", [("Rgn_Cd", "Rgn_Cd (RGN_LKP.csv)")]),
            ("ORDERS_HDR", "RTN_LOG", [("OrdID", "OrdID (RTN_LOG.csv)"), ("line_no", "line_no (RTN_LOG.csv)")]),
        ]:
            rel = sub(rels, "relationship")
            if len(pairs) == 1:
                eq = sub(rel, "expression", {"op": "="})
                sub(eq, "expression", {"op": f"[{pairs[0][0]}]"})
                sub(eq, "expression", {"op": f"[{pairs[0][1]}]"})
            else:
                conj = sub(rel, "expression", {"op": "AND"})
                for a, b in pairs:
                    eq = sub(conj, "expression", {"op": "="})
                    sub(eq, "expression", {"op": f"[{a}]"})
                    sub(eq, "expression", {"op": f"[{b}]"})
            sub(rel, "first-end-point", {"object-id": self._object_id(first)})
            sub(rel, "second-end-point", {"object-id": self._object_id(second)})
        return ds

    def _join_relation_into(self, parent, tag):
        join = sub(parent, tag, {"join": "inner", "type": "join"})
        clause = sub(join, "clause", {"type": "join"})
        expr = sub(clause, "expression", {"op": "="})
        sub(expr, "expression", {"op": "[ORDERS_HDR.csv].[OrdID]"})
        sub(expr, "expression", {"op": "[ord_lines.csv].[OrdID]"})
        self._table_relation(join, "relation", "ORDERS_HDR")
        self._table_relation(join, "relation", "ord_lines")

    def _calc_column(self, parent, c: Calc):
        attrs = {"caption": c.caption, "datatype": c.datatype, "name": f"[{c.internal}]",
                 "role": c.role, "type": c.type}
        if c.caption in PERCENT_FORMAT:
            attrs["default-format"] = "p0.00%"
        col = sub(parent, "column", attrs)
        sub(col, "calculation", {"class": "tableau", "formula": stored_formula(c)})
        return col

    # --- worksheets -----------------------------------------------------------------------------
    def _deps(self, view, calcs: list[str], fields: list[tuple[str, str]], instances: list[tuple]):
        dep = sub(view, "datasource-dependencies", {"datasource": self.ds_name})
        done: list[Calc] = []
        for cap in calcs:
            for c in calc_dependencies(cap):
                if c not in done:
                    done.append(c)
        for local, dtype in fields:
            role = "measure" if dtype in ("real", "integer") else "dimension"
            typ = "quantitative" if role == "measure" else ("ordinal" if dtype == "date" else "nominal")
            sub(dep, "column", {"datatype": dtype, "name": f"[{local}]", "role": role, "type": typ})
        for c in done:
            self._calc_column(dep, c)
        for column, derivation, name, typ, table_calc in instances:
            ci = sub(dep, "column-instance", {"column": column, "derivation": derivation, "name": f"[{name}]",
                                              "pivot": "key", "type": typ})
            if table_calc:
                sub(ci, "table-calc", {"ordering-type": "Rows"})

    def _year_filter(self, view, context: bool = False):
        attrs = {"class": "categorical", "column": self.ref("yr:OrdDt:ok")}
        if context:
            attrs["context"] = "true"
        flt = sub(view, "filter", attrs)
        sub(flt, "groupfilter", {"function": "member", "level": "[yr:OrdDt:ok]", "member": "2025",
                                 U + "ui-domain": "database", U + "ui-enumeration": "inclusive",
                                 U + "ui-marker": "enumerate"})

    def _worksheet(self, worksheets, name: str):
        ws = sub(worksheets, "worksheet", {"name": name})
        table = sub(ws, "table")
        view = sub(table, "view")
        dss = sub(view, "datasources")
        sub(dss, "datasource", {"caption": "ORDERS_HDR+ (legacy_csv)", "name": self.ds_name})
        return ws, table, view, dss

    def _finish(self, ws, table, view, slices: list[str], encodings: list[tuple[str, str]],
                rows: str | None, cols: str | None):
        sl = sub(view, "slices")
        for s in slices:
            sub(sl, "column", text=s)
        sub(view, "aggregation", {"value": "true"})
        sub(table, "style")
        panes = sub(table, "panes")
        pane = sub(panes, "pane", {"selection-relaxation-option": "selection-relaxation-allow"})
        sub(sub(pane, "view"), "breakdown", {"value": "auto"})
        sub(pane, "mark", {"class": "Automatic"})
        if encodings:
            enc = sub(pane, "encodings")
            for kind, column in encodings:
                sub(enc, kind, {"column": column})
        sub(table, "rows", text=rows)
        sub(table, "cols", text=cols)
        sub(ws, "simple-id", {"uuid": _guid("ws:" + ws.get("name"))})

    YEAR_INST = ("[OrdDt]", "Year", "yr:OrdDt:ok", "ordinal", False)

    def _usr(self, caption: str, table_calc: bool = False):
        c = CALC_BY_CAPTION[caption]
        return (f"[{c.internal}]", "User", f"usr:{c.internal}:qk", "quantitative", table_calc)

    def _sum(self, caption_or_field: str):
        c = CALC_BY_CAPTION.get(caption_or_field)
        inner = c.internal if c else caption_or_field
        return (f"[{inner}]", "Sum", f"sum:{inner}:qk", "quantitative", False)

    def _none(self, field: str, pivot: str = "nk"):
        return (f"[{field}]", "None", f"none:{field}:{pivot}", "nominal" if pivot == "nk" else "ordinal", False)

    def build_worksheets(self, root):
        wss = sub(root, "worksheets")
        year = self.ref("yr:OrdDt:ok")
        net = self.ref(self.calc_inst("Net Revenue"))

        # 1 KPI Summary
        ws, table, view, _ = self._worksheet(wss, "KPI Summary")
        kpi_insts = [self._usr("Net Revenue"), self._sum("Gross Profit"), self._usr("GP Margin %"),
                     self._usr("Orders"), self._usr("AOV"), self._usr("Return Rate"), self._sum("Discount Amount"),
                     self._sum("RtnAmt"), self.YEAR_INST]
        self._deps(view, ["Net Revenue", "Gross Profit", "GP Margin %", "Orders", "AOV", "Return Rate",
                          "Discount Amount"], [("OrdDt", "date"), ("RtnAmt", "real"), ("OrdID", "string")],
                   kpi_insts)
        mn = sub(view, "filter", {"class": "categorical", "column": self.ref(":Measure Names")})
        union = sub(mn, "groupfilter", {"function": "union", U + "op": "manual"})
        for inst in kpi_insts[:-1]:
            sub(union, "groupfilter", {"function": "member", "level": "[:Measure Names]",
                                       "member": f'"{self.ref(inst[2])}"'})
        self._year_filter(view)
        self._finish(ws, table, view, [self.ref(":Measure Names"), year],
                     [("text", self.ref("Multiple Values"))], self.ref(":Measure Names"), None)

        # 2 Revenue by Region
        ws, table, view, _ = self._worksheet(wss, "Revenue by Region")
        self._deps(view, ["Net Revenue", "Gross Profit"], [("OrdDt", "date"), ("Rgn_Nm", "string")],
                   [self._none("Rgn_Nm"), self._usr("Net Revenue"), self._sum("Gross Profit"), self.YEAR_INST])
        self._year_filter(view)
        self._finish(ws, table, view, [year], [("tooltip", self.ref(self.calc_inst("Gross Profit", "sum")))],
                     self.ref("none:Rgn_Nm:nk"), net)

        # 3 Monthly Trend (table calculation)
        ws, table, view, _ = self._worksheet(wss, "Monthly Trend")
        self._deps(view, ["Net Revenue", "Running Net Revenue"], [("OrdDt", "date")],
                   [("[OrdDt]", "Month-Trunc", "tmn:OrdDt:qk", "quantitative", False), self._usr("Net Revenue"),
                    self._usr("Running Net Revenue", table_calc=True), self.YEAR_INST])
        self._year_filter(view)
        self._finish(ws, table, view, [year], [],
                     f"({net} / {self.ref(self.calc_inst('Running Net Revenue'))})", self.ref("tmn:OrdDt:qk"))

        # 4 Category Profitability
        ws, table, view, _ = self._worksheet(wss, "Category Profitability")
        self._deps(view, ["Gross Profit", "GP Margin %"], [("OrdDt", "date"), ("CatNm", "string")],
                   [self._none("CatNm"), self._sum("Gross Profit"), self._usr("GP Margin %"), self.YEAR_INST])
        self._year_filter(view)
        self._finish(ws, table, view, [year], [("color", self.ref(self.calc_inst("GP Margin %")))],
                     self.ref("none:CatNm:nk"), self.ref(self.calc_inst("Gross Profit", "sum")))

        # 5 Top Products (context filter + Top N parameter)
        ws, table, view, dss = self._worksheet(wss, "Top Products")
        sub(dss, "datasource", {"name": "Parameters"})
        pdep = sub(view, "datasource-dependencies", {"datasource": "Parameters"})
        self._parameter_column(pdep)
        self._deps(view, ["Net Revenue"], [("OrdDt", "date"), ("ProdNm", "string")],
                   [self._none("ProdNm"), self._usr("Net Revenue"), self.YEAR_INST])
        top = sub(view, "filter", {"class": "categorical", "column": self.ref("none:ProdNm:nk")})
        end = sub(top, "groupfilter", {"count": "[Parameters].[Parameter 1]", "end": "top", "function": "end",
                                       "units": "records", U + "ui-marker": "end", U + "ui-top-by-field": "true"})
        order = sub(end, "groupfilter", {"direction": "DESC",
                                         "expression": f"[{CALC_BY_CAPTION['Net Revenue'].internal}]",
                                         "function": "order", U + "ui-marker": "order"})
        sub(order, "groupfilter", {"function": "level-members", "level": "[none:ProdNm:nk]",
                                   U + "ui-enumeration": "all", U + "ui-marker": "enumerate"})
        self._year_filter(view, context=True)
        self._finish(ws, table, view, [year, self.ref("none:ProdNm:nk")], [], self.ref("none:ProdNm:nk"), net)

        # 6 Customer Cohorts (FIXED LOD; ordinary year filter)
        ws, table, view, _ = self._worksheet(wss, "Customer Cohorts")
        cohort = CALC_BY_CAPTION["Cohort Year"].internal
        self._deps(view, ["Cohort Year", "Net Revenue", "Orders"], [("OrdDt", "date"), ("CustNo", "string")],
                   [(f"[{cohort}]", "None", f"none:{cohort}:ok", "ordinal", False), self._usr("Net Revenue"),
                    self._usr("Orders"), self.YEAR_INST])
        self._year_filter(view)
        self._finish(ws, table, view, [year], [("text", self.ref(self.calc_inst("Orders")))],
                     self.ref(f"none:{cohort}:ok"), net)
        return wss

    # --- parameters, dashboard, windows ---------------------------------------------------------
    def _parameter_column(self, parent):
        col = sub(parent, "column", {"caption": "Top N", "datatype": "integer", "name": "[Parameter 1]",
                                     "param-domain-type": "range", "role": "measure", "type": "quantitative",
                                     "value": "10"})
        sub(col, "calculation", {"class": "tableau", "formula": "10"})
        sub(col, "range", {"granularity": "5", "max": "50", "min": "5"})
        return col

    def build_parameters(self, datasources):
        ds = sub(datasources, "datasource", {"hasconnection": "false", "inline": "true", "name": "Parameters",
                                             "version": VERSION})
        sub(ds, "aliases", {"enabled": "yes"})
        self._parameter_column(ds)

    def build_dashboard(self, root):
        dbs = sub(root, "dashboards")
        db = sub(dbs, "dashboard", {"name": "Sales Performance"})
        sub(db, "style")
        sub(db, "size", {"maxheight": "900", "maxwidth": "1200", "minheight": "900", "minwidth": "1200"})
        zones = sub(db, "zones")
        outer = sub(zones, "zone", {"h": "100000", "id": "1", "type-v2": "layout-basic", "w": "100000",
                                    "x": "0", "y": "0"})
        layout = [("KPI Summary", 0, 0, 100000, 30000), ("Revenue by Region", 0, 30000, 50000, 35000),
                  ("Monthly Trend", 50000, 30000, 50000, 35000), ("Category Profitability", 0, 65000, 100000, 35000)]
        for i, (name, x, y, w, h) in enumerate(layout, start=2):
            sub(outer, "zone", {"h": h, "id": i, "name": name, "w": w, "x": x, "y": y})
        sub(db, "simple-id", {"uuid": _guid("db:Sales Performance")})

    def build_windows(self, root):
        wins = sub(root, "windows", {"source-height": "30"})
        for name in ["KPI Summary", "Revenue by Region", "Monthly Trend", "Category Profitability",
                     "Top Products", "Customer Cohorts"]:
            w = sub(wins, "window", {"class": "worksheet", "name": name})
            sub(w, "simple-id", {"uuid": _guid("win:" + name)})
        w = sub(wins, "window", {"class": "dashboard", "maximized": "true", "name": "Sales Performance"})
        sub(w, "simple-id", {"uuid": _guid("win:Sales Performance")})

    def build(self) -> etree._Element:
        root = etree.Element("workbook", nsmap={"user": USER_NS})
        root.set("original-version", VERSION)
        root.set("source-build", SOURCE_BUILD)
        root.set("source-platform", "win")
        root.set("version", VERSION)
        manifest = sub(root, "document-format-change-manifest")
        for feature in ("ObjectModelEncapsulateLegacy", "ObjectModelRelationshipPerfOptions",
                        "ObjectModelTableType", "SchemaViewerObjectModel"):
            sub(manifest, f"_.fcp.{feature}.true...{feature}")
        sub(manifest, "SheetIdentifierTracking")
        sub(manifest, "WindowsPersistSimpleIdentifiers")
        prefs = sub(root, "preferences")
        sub(prefs, "preference", {"name": "ui.encoding.shelf.height", "value": "24"})
        sub(prefs, "preference", {"name": "ui.shelf.height", "value": "26"})
        datasources = sub(root, "datasources")
        self.build_parameters(datasources)
        self.build_datasource(datasources)
        self.build_worksheets(root)
        self.build_dashboard(root)
        self.build_windows(root)
        return root


def serialize(root: etree._Element) -> bytes:
    body = etree.tostring(root, pretty_print=True, encoding="utf-8")
    return b"<?xml version='1.0' encoding='utf-8' ?>\n\n" + body


def write_twb(csv_dir: Path, out_path: Path, connection_directory: str | None = None) -> Path:
    wb = Workbook(connection_directory or csv_dir.resolve().as_posix(), read_headers(csv_dir))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(serialize(wb.build()))
    return out_path


def write_twbx(csv_dir: Path, out_path: Path) -> Path:
    """Packaged workbook: the .twb points at Data/legacy_csv inside the archive, CSVs included."""
    wb = Workbook("Data/legacy_csv", read_headers(csv_dir))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fixed_time = (2026, 10, 30, 0, 0, 0)  # constant timestamps keep the archive reproducible
    with zipfile.ZipFile(out_path, "w", compression=zipfile.ZIP_DEFLATED) as z:
        info = zipfile.ZipInfo(out_path.stem + ".twb", date_time=fixed_time)
        info.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(info, serialize(wb.build()))
        for t in TABLES:
            info = zipfile.ZipInfo(f"Data/legacy_csv/{t}.csv", date_time=fixed_time)
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, (csv_dir / f"{t}.csv").read_bytes())
    return out_path
